#!/usr/bin/env python3
"""Generates BodyMapShapes.kt from the react-body-highlighter polygons (MIT, (c) 2020 GV79).

Usage: build.py path/to/react-body-highlighter/src/assets/index.ts > BodyMapShapes.kt
"""
import re
import sys

GROUP = {
    "CHEST": "CHEST", "OBLIQUES": "CORE", "ABS": "CORE",
    "BICEPS": "ARMS", "TRICEPS": "ARMS", "FOREARM": "ARMS",
    "NECK": "SHOULDERS", "FRONT_DELTOIDS": "SHOULDERS", "BACK_DELTOIDS": "SHOULDERS",
    "TRAPEZIUS": "BACK", "UPPER_BACK": "BACK", "LOWER_BACK": "BACK",
    "ABDUCTORS": "LEGS", "ABDUCTOR": "LEGS", "QUADRICEPS": "LEGS", "CALVES": "LEGS",
    "GLUTEAL": "LEGS", "HAMSTRING": "LEGS", "LEFT_SOLEUS": "LEGS", "RIGHT_SOLEUS": "LEGS",
    "HEAD": None, "KNEES": None,
}

src = open(sys.argv[1]).read()
sections = {}
for name in ("anteriorData", "posteriorData"):
    m = re.search(r"export const %s[^=]*=\s*\[(.*?)\n\];" % name, src, re.S)
    sections[name] = m.group(1)

def parse(block):
    out = []
    for m in re.finditer(r"muscle: MuscleType\.(\w+),\s*svgPoints: \[(.*?)\],\s*\}", block, re.S):
        group = GROUP[m.group(1)]
        for pts in re.findall(r"'([^']+)'", m.group(2)):
            nums = [float(x) for x in pts.split()]
            out.append((m.group(1), group, nums))
    return out

print("""package com.boratreino.feature.progress

import com.boratreino.core.model.MuscleGroup

// GENERATED by tools/body_map/build.py: do not edit by hand.
// Outlines from react-body-highlighter (MIT License, Copyright (c) 2020 GV79).
// See THIRD_PARTY_NOTICES.md.

/** One piece of the body on the 100 x 220 grid; [group] is null for pieces that are never shaded (head, knees). */
internal class BodyShape(val group: MuscleGroup?, val points: FloatArray)

internal object BodyMapShapes {
    const val WIDTH = 100f
    const val HEIGHT = 220f
""")
for label, key in (("front", "anteriorData"), ("back", "posteriorData")):
    print("    val %s: List<BodyShape> = listOf(" % label)
    for _, g, nums in parse(sections[key]):
        gs = "MuscleGroup.%s" % g if g else "null"
        vals = ", ".join(("%g" % round(n, 1)) + "f" for n in nums)
        print("        BodyShape(%s, floatArrayOf(%s))," % (gs, vals))
    print("    )\n")
print("}")
